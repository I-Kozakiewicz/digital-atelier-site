const root = document.documentElement;
const menu = document.getElementById('menuToggle');
const nav = document.getElementById('nav');
const languageGroup = document.querySelector('.lang');
const languageButtons = languageGroup.querySelectorAll('[data-lang]');
const heroImage = document.querySelector('.hero-art img');
const demoLinks = [...document.querySelectorAll('[data-template-demo]')].map(link => ({ link, path: link.getAttribute('href') }));

function setMenu(open) {
  nav.classList.toggle('open', open);
  menu.setAttribute('aria-expanded', String(open));
  menu.setAttribute('aria-label', labels[root.lang].menu[Number(open)]);
}

function setLanguage(lang) {
  const translations = copy[lang];
  root.lang = lang;
  root.dir = lang === 'ar' ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    element.textContent = translations[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    element.innerHTML = translations[element.dataset.i18nHtml];
  });
  languageButtons.forEach(button => {
    const selected = button.dataset.lang === lang;
    button.classList.toggle('active', selected);
    button.setAttribute('aria-pressed', String(selected));
  });

  nav.setAttribute('aria-label', labels[lang].nav);
  languageGroup.setAttribute('aria-label', labels[lang].language);
  document.title = translations.pageTitle;
  document.querySelector('meta[name="description"]').setAttribute('content', translations.pageDescription);
  heroImage.alt = labels[lang].image;
  document.querySelector('.project-sen img').alt = translations.projectSenAlt;
  document.querySelector('.project-clinic img').alt = translations.projectClinicAlt;
  demoLinks.forEach(({ link, path }) => { link.href = path + '?lang=' + lang; });
  setMenu(false);
  try {
    localStorage.setItem('da-language', lang);
  } catch {
    // Language switching still works when browser storage is unavailable.
  }
}

languageButtons.forEach(button => {
  button.addEventListener('click', () => setLanguage(button.dataset.lang));
});
menu.addEventListener('click', () => setMenu(!nav.classList.contains('open')));
nav.querySelectorAll('a').forEach(link => link.addEventListener('click', () => setMenu(false)));
document.addEventListener('keydown', event => {
  if (event.key === 'Escape' && nav.classList.contains('open')) {
    setMenu(false);
    menu.focus();
  }
});
document.getElementById('year').textContent = new Date().getFullYear();

